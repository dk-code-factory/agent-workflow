// Called only by acceptance.mjs after its explicit --run-privileged gate.
// Uses installed clients and disposable configuration; never installs hooks or
// replaces a host socket/configuration file.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const execute = (command, args, env) => new Promise((resolve, reject) => {
  const child = spawn(command, args, { env, stdio: ['ignore', 'pipe', 'pipe'] });
  let stdout = '', stderr = '';
  const timer = setTimeout(() => child.kill('SIGKILL'), 30000);
  child.stdout.on('data', data => { stdout += data; });
  child.stderr.on('data', data => { stderr += data; });
  child.once('error', error => { clearTimeout(timer); reject(error); });
  child.once('close', (code, signal) => { clearTimeout(timer); resolve({ code, signal, stdout: stdout.trim(), stderr: stderr.trim() }); });
});

export async function checkAPIFencing({ runtime, name, dir, reference, image, netns, ownedNetworks, ownedContainers }) {
  // Missing Docker is an unmet acceptance prerequisite, never silent coverage.
  for (const client of ['podman', 'docker']) {
    const result = await execute(client, ['--version'], process.env);
    assert.equal(result.code, 0, `${client} CLI must be installed for privileged API-fencing acceptance: ${result.stderr}`);
  }
  const base = join(dir, 'api-fencing');
  const home = join(base, 'home');
  const containers = join(home, '.config', 'containers');
  const docker = join(home, '.docker');
  const bin = join(base, 'bin');
  for (const path of [containers, docker, bin]) mkdirSync(path, { recursive: true });
  const socket = join(base, 'outside.sock');
  const requests = [];
  const recorder = createServer((request, response) => {
    requests.push({ method: request.method, url: request.url });
    request.resume();
    // A leaking client gets only a fixture response; no outside engine exists.
    response.writeHead(500, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify({ message: 'outside API recorder: routing escaped runtime' }));
  });
  recorder.listen(socket);
  await once(recorder, 'listening');
  recorder.unref(); // Setup errors must not leave the acceptance process waiting.
  const outside = 'unix://' + socket;
  const connections = join(containers, 'podman-connections.json');
  writeFileSync(connections, JSON.stringify({ Connection: { Default: 'outside', Connections: { outside: { URI: outside, Identity: '', IsMachine: false } } } }));
  const noConnections = join(base, 'empty-connections.json');
  writeFileSync(noConnections, JSON.stringify({ Connection: { Connections: {} } }));
  writeFileSync(join(containers, 'containers.conf'), `[engine]\nremote = true\nactive_service = "outside"\n[engine.service_destinations.outside]\nuri = ${JSON.stringify(outside)}\nidentity = ""\n`);
  // Real Docker metadata is generated by its own CLI, avoiding invented IDs or
  // metadata schemas. It only writes this disposable configuration directory.
  const env = { ...process.env, HOME: home, XDG_CONFIG_HOME: join(home, '.config'), DOCKER_CONFIG: docker, PODMAN_CONNECTIONS_CONF: connections, PATH: bin + ':' + process.env.PATH };
  for (const key of ['DOCKER_HOST', 'CONTAINER_HOST', 'DOCKER_CONTEXT', 'CONTAINER_CONNECTION', 'CONTAINERS_CONF', 'CONTAINERS_CONF_OVERRIDE', 'CONTAINERS_CONF_MODULES']) delete env[key];
  const context = await execute('docker', ['context', 'create', 'outside', '--docker', 'host=' + outside], env);
  assert.equal(context.code, 0, context.stderr);
  const dockerConfig = join(docker, 'config.json');
  const helperTrace = join(base, 'auth-helper.trace');
  const credential = join(base, 'original-auth');
  writeFileSync(credential, 'original fixture authentication\n');
  writeFileSync(join(bin, 'docker-credential-awfixture'), `#!/bin/sh\nset -eu\ncat "$AW_AUTH_ORIGINAL" >> "$AW_AUTH_TRACE"\nprintf '%s\\n' "$1" >> "$AW_AUTH_TRACE"\ncase "$1" in get) printf '%s\\n' '{"Username":"fixture-user","Secret":"fixture-secret"}';; list) printf '%s\\n' '{}';; erase|store) cat >/dev/null;; *) exit 1;; esac\n`, { mode: 0o755 });
  const auths = { 'auth.fixture.invalid': { auth: Buffer.from('fixture-user:fixture-secret').toString('base64') } };
  const config = { currentContext: 'outside', auths, credHelpers: { 'auth.fixture.invalid': 'awfixture' } };
  writeFileSync(dockerConfig, JSON.stringify(config));
  const auth = join(containers, 'auth.json');
  writeFileSync(auth, JSON.stringify({ auths }));
  env.REGISTRY_AUTH_FILE = auth;
  env.AW_AUTH_ORIGINAL = credential;
  env.AW_AUTH_TRACE = helperTrace;
  const originals = new Map([connections, join(containers, 'containers.conf'), dockerConfig, auth].map(path => [path, readFileSync(path, 'utf8')]));
  const routing = ['DOCKER_HOST', 'CONTAINER_HOST', 'DOCKER_CONTEXT', 'CONTAINER_CONNECTION', 'AGENT_WORKFLOW_NETWORK_RUNTIME', 'AGENT_WORKFLOW_NETWORK_REFERENCE'];
  // The descendant starts directly, without Codex or any plugin/hook dispatch,
  // and removes every public routing selector after the launcher ran.
  const insideWith = (environment, ...args) => execute(runtime, ['exec', name, '--', '/bin/sh', '-c', 'exec /usr/bin/env ' + routing.map(key => '-u ' + key).join(' ') + ' "$@"', 'fencing-descendant', ...args], environment);
  const inside = (...args) => insideWith(env, ...args);
  const networks = [];
  const completed = [];
  try {
    const cases = [
      ['podman saved default', ['podman']],
      ['podman named connection', ['podman', '--connection', 'outside']],
      ['podman named containers.conf destination', ['podman', '--remote', '--connection', 'outside'], { ...env, PODMAN_CONNECTIONS_CONF: noConnections }],
      ['docker saved context', ['docker']],
      ['docker named context', ['docker', '--context', 'outside']],
      ['docker default socket', ['docker', '--context', 'default']],
    ];
    for (const [label, client, environment = env] of cases) {
      const network = `${name}-fence-${networks.length}`;
      networks.push(network);
      ownedNetworks.push(network);
      const result = await insideWith(environment, ...client, 'network', 'create', network);
      assert.equal(result.code, 0, `${label}: ${result.stderr}`);
      const inspect = await execute('podman', ['--remote', '--url', reference.endpoint, 'network', 'inspect', network], process.env);
      assert.equal(inspect.code, 0, `${label} did not create its network in the selected runtime: ${inspect.stderr}`);
      assert.equal(requests.filter(request => !['GET', 'HEAD', 'OPTIONS'].includes(request.method)).length, 0, `${label} reached outside API: ${JSON.stringify(requests)}`);
      completed.push(label);
    }
    const login = await inside('podman', 'login', '--get-login', 'auth.fixture.invalid');
    assert.equal(login.code, 0, login.stderr);
    assert.equal(login.stdout, 'fixture-user', 'original Podman authfile was not readable');
    const projectedAuth = await inside('node', '-e', 'const c=JSON.parse(require("node:fs").readFileSync(process.env.DOCKER_CONFIG+"/config.json"));process.stdout.write(JSON.stringify({auths:c.auths,credHelpers:c.credHelpers}))');
    assert.equal(projectedAuth.code, 0, projectedAuth.stderr);
    assert.deepEqual(JSON.parse(projectedAuth.stdout), { auths, credHelpers: config.credHelpers }, 'projected Docker configuration changed authentication fields');
    // Logout exercises Docker's actual credential helper without a registry or
    // model call. Its config save may fail on the intentionally read-only view.
    await inside('docker', 'logout', 'auth.fixture.invalid');
    assert.match(readFileSync(helperTrace, 'utf8'), /original fixture authentication\nerase\n/, 'Docker helper lost access to its original auth path');
    const localName = `${name}-fence-local`;
    ownedContainers.push(localName);
    const local = await inside('sudo', '-n', '/usr/bin/podman', '--remote=false', 'run', '--rm', '--pull=never', '--network=host', '--name', localName, image, 'identity');
    assert.equal(local.code, 0, `explicit local Podman: ${local.stderr}`);
    assert.equal(JSON.parse(local.stdout).netns, netns, 'explicit local Podman escaped runtime network namespace');
    ownedContainers.splice(ownedContainers.indexOf(localName), 1);
    for (const [path, original] of originals) assert.equal(readFileSync(path, 'utf8'), original, `host configuration changed: ${path}`);
    assert.deepEqual(requests, [], 'supported saved/default clients contacted the outside API recorder');
    return { clients: completed, outsideRequests: requests, auth: 'original authfile and Docker credential helper paths readable', explicitLocal: 'host-network container remains in runtime namespace', hooks: 'absent; descendant strips routing environment' };
  } finally {
    const cleanupFailures = [];
    for (const network of networks) {
      const cleanup = await execute('podman', ['--remote', '--url', reference.endpoint, 'network', 'rm', network], process.env);
      if (cleanup.code === 0) ownedNetworks.splice(ownedNetworks.indexOf(network), 1);
      else if (completed.length === networks.length) cleanupFailures.push(`${network}: ${cleanup.stderr}`);
    }
    await execute('podman', ['--remote', '--url', reference.endpoint, 'rm', '-f', `${name}-fence-local`], process.env);
    recorder.closeAllConnections();
    await new Promise(resolve => recorder.close(resolve));
    assert.deepEqual(cleanupFailures, [], 'fencing fixture network cleanup failed; names retained for outer cleanup');
  }
}
